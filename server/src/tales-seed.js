// Split [start, end] of a video into N equal segments (1-dec rounding).
export function distribute(durationSec, n) {
  const start0 = 3;
  const end0 = Math.max(durationSec - 2, start0 + n);
  const step = (end0 - start0) / n;
  const segs = [];
  for (let i = 0; i < n; i++) {
    segs.push({
      start_sec: Math.round((start0 + i * step) * 10) / 10,
      end_sec: Math.round((start0 + (i + 1) * step) * 10) / 10,
    });
  }
  return segs;
}

